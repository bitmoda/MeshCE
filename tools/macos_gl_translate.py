#!/usr/bin/env python3
"""Write the Mac host wrappers that turn guest OpenGL pointers into host pointers.

The ILP32 guest keeps its memory above HALO_MACOS_BIAS. A pointer that fits in
a guest register is only the low 32 bits. Android can pass that value straight
through because the guest is mapped at that address. This host is not, so every
pointer ANGLE reads or writes has to go through guest_pointer.

glVertexAttribPointer and the draw element entry points are the exception.
Those arguments are byte offsets into a bound buffer, and the renderer uses
buffer objects for vertices and indices.
"""

import re
import sys
from pathlib import Path

OFFSET_FUNCTIONS = {
    "glVertexAttribPointer",
    "glVertexAttribIPointer",
    "glDrawElements",
    "glDrawElementsBaseVertex",
    "glDrawElementsBaseVertexEXT",
    "glDrawElementsBaseVertexOES",
}


def prototypes(*headers):
    result = {}
    pattern = re.compile(r"GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(\w+)\s*\((.*?)\);", re.S)
    for header in headers:
        text = Path(header).read_text(encoding="utf-8")
        for ret, name, params in pattern.findall(text):
            params = " ".join(params.split())
            result.setdefault(name, (ret.strip(), params))
    return result


def split_parameter(param):
    param = param.strip()
    match = re.match(r"(.*?)(\w+)\s*$", param)
    ptype, pname = match.group(1).strip(), match.group(2)
    if not ptype:
        ptype, pname = param, None
    return ptype, pname


def host_prototypes(guest_gl):
    result = {}
    pattern = re.compile(r"^(.+?) hostgl_(\w+)\((.*)\);$", re.M)
    for ret, name, params in pattern.findall(Path(guest_gl).read_text(encoding="utf-8")):
        if ret.strip() == "return":
            continue
        if params.strip() == "void":
            parts = []
        else:
            parts = [part.strip() for part in params.split(",")]
        result[name] = (ret.strip(), parts)
    return result


def wrapper(name, ret, host_types, gles_params):
    args = [f"a{index}" for index in range(len(host_types))]
    signature = ", ".join(f"{ptype} {arg}" for ptype, arg in zip(host_types, args)) or "void"
    if name == "glShaderSource":
        body = [
            "\tconst unsigned long long *wide = strings ? guest_pointer((uint64_t)(uintptr_t)strings) : 0;",
            "\tconst GLchar *local[16];",
            "\tGLsizei limit = count > 16 ? 16 : count;",
            "\tGLsizei index;",
            "\tfor (index = 0; index < limit; index++)",
            "\t\tlocal[index] = guest_pointer(wide[index]);",
            "\tglShaderSource(shader, limit, local,",
            "\t\tlengths ? (const GLint *)guest_pointer((uint64_t)(uintptr_t)lengths) : 0);",
        ]
        return (
            "static void bridge_glShaderSource(GLuint shader, GLsizei count, "
            "const unsigned long long *strings, const GLint *lengths)\n{\n" + "\n".join(body) + "\n}"
        )
    calls = []
    for index, (host_type, gles_param) in enumerate(zip(host_types, gles_params)):
        gles_type, _ = split_parameter(gles_param) if gles_param != "void" else ("void", None)
        arg = args[index]
        if "*" in host_type or (host_type == "unsigned long long" and "*" in gles_type):
            cast = gles_type if "*" in gles_type else "void *"
            value = arg if host_type == "unsigned long long" else f"(uint64_t)(uintptr_t){arg}"
            calls.append(f"({cast})guest_pointer({value})")
        elif host_type == "long long":
            calls.append(f"({gles_type}){arg}")
        else:
            calls.append(arg)
    call = f"{name}({', '.join(calls)})"
    statement = f"return {call};" if ret != "void" else f"{call};"
    return f"static {ret} bridge_{name}({signature})\n{{\n\t{statement}\n}}"


def main():
    guest_gl, gl32, gl2ext, output = sys.argv[1:5]
    gles = prototypes(gl32, gl2ext)
    host = host_prototypes(guest_gl)
    blocks = []
    names = []
    for name, (ret, host_types) in host.items():
        if name in OFFSET_FUNCTIONS or name not in gles:
            continue
        gles_ret, gles_params = gles[name]
        if gles_params in ("void", ""):
            gles_list = []
        else:
            gles_list = [part.strip() for part in gles_params.split(",")]
        if len(gles_list) != len(host_types):
            raise SystemExit(f"{name}: host has {len(host_types)} args, GLES has {len(gles_list)}")
        pointer = any("*" in ptype or (ptype == "unsigned long long") for ptype in host_types)
        if not pointer:
            continue
        if ret != gles_ret:
            raise SystemExit(f"{name}: return {ret} does not match {gles_ret}")
        blocks.append(wrapper(name, ret, host_types, gles_list))
        names.append(name)
    lines = [
        "/* Guest OpenGL pointers, rebased onto the Mac arena. Generated by tools/macos_gl_translate.py. */",
        '#include "host.h"',
        "#include <GLES3/gl32.h>",
        "#include <GLES2/gl2ext.h>",
        "#include <string.h>",
        "",
        *blocks,
        "",
        "void *host_gl_bridge(const char *name)",
        "{",
    ]
    for name in names:
        lines.append(f'\tif (!strcmp(name, "{name}"))')
        lines.append(f"\t\treturn (void *)bridge_{name};")
    lines += ["\treturn 0;", "}", ""]
    Path(output).write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(names)} wrappers")


if __name__ == "__main__":
    main()
